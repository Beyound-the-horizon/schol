"""Canonical SQLAlchemy entity model for public.scholarships.

Reconciles the crawler's structured domain model with platform lifecycle
and audit tracking fields. Works transparently on both PostgreSQL (JSONB)
and SQLite (JSON).
"""

from datetime import date, datetime
from typing import Any, Dict, List, Optional, Union
from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    Index,
    Integer,
    JSON,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    """Base declarative class for all SQLAlchemy models."""
    pass


class ScholarshipModel(Base):
    """Canonical Scholarship entity model."""

    __tablename__ = "scholarships"

    # Numeric primary key: PostgreSQL INTEGER generated by scholarships_id_seq
    id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
        autoincrement=True,
        index=True,
    )

    # Core identification & provider fields
    name: Mapped[str] = mapped_column(String(300), nullable=False, index=True)
    provider: Mapped[Optional[str]] = mapped_column(String(300), nullable=True)
    host_country: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)

    # Structured academic scope
    degree_level: Mapped[Optional[Union[List[str], Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), nullable=True
    )
    eligible_countries: Mapped[Optional[Union[List[str], Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), nullable=True
    )
    fields_of_study: Mapped[Optional[Union[List[str], Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), nullable=True
    )

    # Dates & Timelines
    application_open_date: Mapped[Optional[date]] = mapped_column(Date, nullable=True)
    deadline: Mapped[Optional[date]] = mapped_column(Date, nullable=True, index=True)
    deadline_timezone: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)

    # Specific Eligibility Criteria
    minimum_cgpa: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    age_limit: Mapped[Optional[str]] = mapped_column(String(200), nullable=True)
    other_eligibility: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    language_tests: Mapped[Optional[Union[Dict[str, Any], List[Any], Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), nullable=True
    )

    # Financial & Award Details
    funding_coverage: Mapped[Optional[Union[Dict[str, Any], List[Any], str, Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), nullable=True
    )
    award_duration: Mapped[Optional[str]] = mapped_column(String(200), nullable=True)

    # Application Requirements
    required_documents: Mapped[Optional[Union[List[str], Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), nullable=True
    )
    essay_requirements: Mapped[Optional[Union[Dict[str, Any], List[Any], Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), nullable=True
    )
    referee_requirements: Mapped[Optional[Union[Dict[str, Any], List[Any], Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), nullable=True
    )
    application_fee_and_effort: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Verification & Source Provenance
    official_url: Mapped[Optional[str]] = mapped_column(Text, unique=True, nullable=True)
    last_verified_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # Platform Lifecycle & Governance (Draft by default)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    is_published: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    publication_status: Mapped[str] = mapped_column(
        String(50), nullable=False, default="draft", server_default="draft"
    )
    reviewed_by: Mapped[Optional[str]] = mapped_column(String(200), nullable=True)
    reviewed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    published_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    rejection_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    audit_log: Mapped[Optional[Union[List[Dict[str, Any]], Any]]] = mapped_column(
        JSON().with_variant(JSONB, "postgresql"), nullable=True, default=list
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    __table_args__ = (
        # Enforce that is_published and publication_status cannot contradict each other.
        # PostgreSQL enforces this at the DB layer; SQLite enforces it via CHECK on DDL.
        CheckConstraint(
            "(is_published = TRUE AND publication_status = 'published') OR "
            "(is_published = FALSE AND publication_status IN ('draft', 'rejected', 'archived'))",
            name="chk_publication_status_is_published",
        ),
        Index("idx_scholarships_is_published", "is_published"),
        Index("idx_scholarships_publication_status", "publication_status"),
        Index("idx_scholarships_host_country", "host_country"),
        Index("idx_scholarships_provider", "provider"),
    )
